/*
 * One-shot generator for js/lifetables.js — remaining life expectancy by
 * age, sex and country, from the UN World Population Prospects 2024
 * abridged life tables (medium variant). Life expectancy at birth counts
 * every childhood death; an adult's own expectancy is higher, and this
 * table is what lets the countdown use it.
 *
 * Download (public, ~150 MB):
 *   https://population.un.org/wpp/assets/Excel%20Files/1_Indicator%20(Standard)/CSV_FILES/WPP2024_Life_Table_Abridged_Medium_2024-2100.csv.gz
 * Run: node tools/gen-lifetables.js <that .csv.gz or an extracted .csv> [year]
 */
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const readline = require('readline');

const src = process.argv[2];
const YEAR = process.argv[3] || '2025';
if (!src) {
  console.error('usage: node tools/gen-lifetables.js <WPP2024_Life_Table_Abridged_*.csv[.gz]> [year]');
  process.exit(1);
}

// Minimal CSV row split: WPP quotes location names that contain commas.
function splitCsv(line) {
  const out = [];
  let cur = '';
  let q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}

(async () => {
  let stream = fs.createReadStream(src);
  if (/\.gz$/.test(src)) stream = stream.pipe(zlib.createGunzip());
  const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });

  let col = null;
  const tables = {}; // iso3 → { m: {age: ex}, f: {age: ex} }
  const ages = new Set();
  for await (const raw of rl) {
    const row = splitCsv(raw.replace(/^﻿/, ''));
    if (!col) {
      col = {};
      row.forEach((name, i) => { col[name] = i; });
      continue;
    }
    if (row[col.Time] !== YEAR) continue;
    const sex = row[col.Sex] === 'Male' ? 'm' : row[col.Sex] === 'Female' ? 'f' : null;
    if (!sex) continue;
    let iso3 = row[col.ISO3_code];
    if (row[col.LocTypeName] === 'World') iso3 = 'WLD';
    else if (row[col.LocTypeName] !== 'Country/Area' || !iso3) continue;
    const age = Number(row[col.AgeGrpStart]);
    ages.add(age);
    const t = tables[iso3] || (tables[iso3] = { m: {}, f: {} });
    t[sex][age] = Math.round(Number(row[col.ex]) * 10) / 10;
  }

  const ageList = Array.from(ages).sort((a, b) => a - b);
  const compact = {};
  Object.keys(tables).sort().forEach((iso3) => {
    const t = tables[iso3];
    const m = ageList.map((a) => t.m[a]);
    const f = ageList.map((a) => t.f[a]);
    if (m.some((v) => v == null) || f.some((v) => v == null)) return; // incomplete → World fallback
    compact[iso3] = [m, f];
  });
  if (!compact.WLD) throw new Error('no World table for ' + YEAR);

  const out = `/*
 * Memento — remaining life expectancy by exact age (GENERATED by
 * tools/gen-lifetables.js, do not edit). UN World Population Prospects 2024,
 * abridged life tables, medium variant, year ${YEAR}.
 * tables[iso3] = [male ex per age, female ex per age]; ages = age starts.
 */
(function (root) {
  root.MementoLifeTables = {
    source: 'UN WPP 2024',
    year: ${YEAR},
    ages: ${JSON.stringify(ageList)},
    tables: {
${Object.keys(compact).map((k) => `      ${k}: ${JSON.stringify(compact[k])},`).join('\n')}
    },
  };
})(typeof self !== 'undefined' ? self : this);
`;
  const dest = path.join(__dirname, '..', 'js', 'lifetables.js');
  fs.writeFileSync(dest, out);
  console.log(`wrote ${dest}: ${Object.keys(compact).length} tables, ${ageList.length} ages, ${out.length} bytes`);
})().catch((e) => { console.error(e); process.exit(1); });
