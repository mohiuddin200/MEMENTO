/*
 * One-shot generator for js/baseline.js — the offline fallback data.
 * Pulls the World aggregate + the real-country list from the World Bank API
 * and writes a browser/Node-loadable file. Run: node tools/gen-baseline.js
 */
'use strict';
const https = require('https');
const fs = require('fs');
const path = require('path');

function getJSON(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      let body = '';
      res.on('data', (c) => (body += c));
      res.on('end', () => {
        try { resolve(JSON.parse(body)); } catch (e) { reject(e); }
      });
    }).on('error', reject);
  });
}

async function wld(indicator) {
  const j = await getJSON(`https://api.worldbank.org/v2/country/WLD/indicator/${indicator}?format=json&mrnev=1`);
  return j[1][0];
}

(async () => {
  const [leM, leF, dr, br, pop, countries] = await Promise.all([
    wld('SP.DYN.LE00.MA.IN'),
    wld('SP.DYN.LE00.FE.IN'),
    wld('SP.DYN.CDRT.IN'),
    wld('SP.DYN.CBRT.IN'),
    wld('SP.POP.TOTL'),
    getJSON('https://api.worldbank.org/v2/country?format=json&per_page=400'),
  ]);
  const real = countries[1]
    .filter((c) => c.region && c.region.value !== 'Aggregates')
    .map((c) => [c.id, c.name])
    .sort((a, b) => a[1].localeCompare(b[1]));

  const world = {
    name: 'World',
    leMale: leM.value, leFemale: leF.value,
    deathRate: dr.value, birthRate: br.value,
    population: pop.value, year: leM.date,
  };
  const out = `/*
 * Memento — hardcoded baseline (GENERATED by tools/gen-baseline.js, do not edit).
 * Used when the World Bank API is unreachable and no cache exists, so the
 * page never renders empty. World aggregate figures, World Bank Open Data.
 */
(function (root) {
  root.MementoBaseline = {
    fetchedAt: '${new Date().toISOString().slice(0, 10)}',
    world: ${JSON.stringify(world, null, 2)},
    list: ${JSON.stringify(real)}
  };
})(typeof self !== 'undefined' ? self : this);
`;
  fs.writeFileSync(path.join(__dirname, '..', 'js', 'baseline.js'), out);
  console.log(`baseline.js written: world ${JSON.stringify(world)} + ${real.length} countries`);
})().catch((e) => { console.error(e); process.exit(1); });
